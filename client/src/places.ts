export function divisionNames(): string[] {
  return PLACES.map((division) => division.name);
}

export function mandalNames(division: string): string[] {
  return PLACES.find((item) => samePlace(item.name, division))?.mandals.map((mandal) => mandal.name) ?? [];
}

export function villageNames(division: string, mandal: string): string[] {
  const match = PLACES.find((item) => samePlace(item.name, division));
  return match?.mandals.find((item) => samePlace(item.name, mandal))?.villages ?? [];
}

export function divisionForMandal(mandal: string): string {
  const match = PLACES.find((division) => division.mandals.some((item) => samePlace(item.name, mandal)));
  return match?.name ?? "";
}

function placeKey(value: string): string {
  return value.trim().toLowerCase().replace(/\s+/g, " ").replace(/sattenapalle\b/g, "sattenapalli");
}

export function samePlace(left: string, right: string): boolean {
  return placeKey(left) === placeKey(right);
}

export function withCurrent(options: string[], current: string): string[] {
  const trimmed = current.trim();
  if (!trimmed || options.some((item) => samePlace(item, trimmed))) return options;
  return [trimmed, ...options];
}

function official(options: string[], current: string): string {
  return options.find((item) => samePlace(item, current)) || current.trim();
}

export function alignPlace(input: { division?: string; mandal?: string; village?: string }): { division: string; mandal: string; village: string } {
  const division = input.division?.trim() || divisionForMandal(input.mandal || "");
  const mandal = official(mandalNames(division), input.mandal || "");
  const village = official(villageNames(division, mandal), input.village || "");
  return { division, mandal, village };
}

function looseParts(value: string): string[] {
  return value.split(",").map((part) => part.trim()).filter(Boolean);
}

function knownDivision(value: string): string {
  return divisionNames().find((name) => samePlace(name, value)) || divisionForMandal(value);
}

export function matchesPlace(record: { division?: string; mandal?: string; village?: string; place?: string }, filter: { division: string; mandal: string; village: string }): boolean {
  const structured = Boolean((record.division || record.mandal || record.village || "").trim());
  if (structured) {
    if (filter.village && !samePlace(record.village || "", filter.village)) return false;
    if (filter.mandal && !samePlace(record.mandal || "", filter.mandal)) return false;
    if (!filter.division) return true;
    if (record.division && samePlace(record.division, filter.division)) return true;
    return samePlace(divisionForMandal(record.mandal || ""), filter.division);
  }
  const parts = looseParts(record.place || "");
  if (filter.village && !parts.some((part) => samePlace(part, filter.village))) return false;
  if (filter.mandal && !parts.some((part) => samePlace(part, filter.mandal))) return false;
  if (!filter.division) return true;
  return parts.some((part) => samePlace(part, filter.division) || samePlace(knownDivision(part), filter.division));
}
